import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectNlsEntries, placeholders } from './nls-utils.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const sourceArgument = process.argv.indexOf('--source-dir');
const sourceDirectory = sourceArgument >= 0 ? process.argv[sourceArgument + 1] : undefined;
const definition = JSON.parse(await fs.readFile(path.join(root, 'locales/sources.json'), 'utf8'));
const contents = Object.create(null);
const sources = [];
for (const source of definition.sources) {
	let raw;
	if (sourceDirectory) raw = await fs.readFile(path.join(sourceDirectory, source.file), 'utf8');
	else {
		const response = await fetch(source.url, { signal: AbortSignal.timeout(30000) });
		if (!response.ok) throw new Error(`${source.url}: HTTP ${response.status}`);
		raw = await response.text();
	}
	sources.push(JSON.parse(raw).contents);
}
const overrides = JSON.parse(await fs.readFile(path.join(root, 'locales/ru-overrides.json'), 'utf8')).contents;
const missing = [];
const entries = collectNlsEntries(root);
for (const { module, key, message } of entries) {
	const translated = [overrides, ...sources]
		.map(source => source[module]?.[key])
		.find(value => typeof value === 'string' && value.length > 0 && placeholders(value) === placeholders(message));
	if (translated === undefined) missing.push(`${module}#${key}: ${message}`);
	else (contents[module] ??= {})[key] = translated;
}
if (missing.length) throw new Error(`Missing ${missing.length} Russian translations:\n${missing.join('\n')}`);
await fs.mkdir(path.join(root, 'public/locales'), { recursive: true });
await fs.writeFile(path.join(root, 'public/locales/ru.json'), JSON.stringify({ contents }) + '\n');
console.log(
	`Generated complete Russian catalog for ${entries.length} NLS calls (${Object.keys(contents).length} modules).`
);

// Updating workbench strings is fast and offline with --source-dir. Refreshing the
// vendored manifest catalogs is explicit because it downloads one file per extension.
if (process.argv.includes('--update-extensions')) {
	const extensionDirectory = path.join(root, 'public/extensions');
	const outputDirectory = path.join(root, 'public/locales/ru/extensions');
	await fs.mkdir(outputDirectory, { recursive: true });
	const extensionIds = [];
	for (const directory of (await fs.readdir(extensionDirectory)).sort()) {
		const extensionRoot = path.join(extensionDirectory, directory);
		let manifest;
		try {
			manifest = JSON.parse(await fs.readFile(path.join(extensionRoot, 'package.json'), 'utf8'));
		} catch {
			continue;
		}
		if (manifest.publisher !== 'vscode') continue;
		const english = JSON.parse(await fs.readFile(path.join(extensionRoot, 'package.nls.json'), 'utf8'));
		const id = `${manifest.publisher}.${manifest.name}`;
		const url = new URL(`extensions/${id}.i18n.json`, definition.sources[0].url).toString();
		const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
		if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
		const bundle = await response.json();
		const translated = bundle.contents?.package;
		for (const [key, value] of Object.entries(english)) {
			const message = typeof value === 'string' ? value : value.message;
			if (
				typeof translated?.[key] !== 'string' ||
				!translated[key].length ||
				placeholders(message) !== placeholders(translated[key])
			) {
				throw new Error(`Invalid built-in Russian translation: ${id}#${key}`);
			}
		}
		await fs.writeFile(path.join(extensionRoot, 'package.nls.ru.json'), JSON.stringify(translated, null, 2) + '\n');
		await fs.writeFile(path.join(outputDirectory, `${id}.i18n.json`), JSON.stringify(bundle) + '\n');
		extensionIds.push(id);
	}
	await fs.writeFile(
		path.join(root, 'src/localization/builtinTranslations.ts'),
		'// Generated by scripts/generate-locales.mjs --update-extensions.\n' +
			`export const RUSSIAN_BUILTIN_EXTENSIONS = new Set(${JSON.stringify(extensionIds, null, '\t')});\n`
	);
	console.log(`Updated ${extensionIds.length} Russian built-in extension catalogs.`);
}
